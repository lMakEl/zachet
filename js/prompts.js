export const sceneSchema = obj({
  fragments: arr(obj({ kind: enm('title', 'point', 'term', 'image'), show: str, note: str, image: str, say: str, page: int, anchor: str })),
});
export const sceneSystem = l => `Ты хороший лектор и пишешь одну сцену озвученной лекции. Каждый фрагмент — это фраза, которую произнесёт голос, и один элемент, который в этот момент появится на экране. ${GUARD} ${lang(l)}

Фрагменты сцены, 4–6 штук:
- первый — kind "title": show — заголовок сцены; say вводит в тему и связывает с предыдущей сценой;
- point — тезис: show — до 10 слов, без точки в конце; note — пустая строка;
- term — определение: show — термин, note — его определение до 18 слов. Не больше одного на сцену;
- image — картинка: image — id из списка картинок, show — подпись до 8 слов. Не больше одной на сцену, только если картинка помогает объяснить; если картинок нет, не используй. Для остальных видов image — пустая строка.

say — живая устная речь, а не пересказ слайда:
- 1–3 коротких предложения, 12–40 слов;
- связки «смотрите», «а теперь», «отсюда следует», вопрос к слушателю или сравнение — где это помогает, без панибратства;
- только то, что есть в материале: новых фактов, чисел и примеров-фактов не добавляй;
- всё написано так, как произносится: формулы, числа со знаками, сокращения и аббревиатуры — словами или по буквам кириллицей с понятным чтением; без скобок, списков, кавычек-ёлочек вокруг кода, ссылок и спецсимволов;
- не начинай каждую фразу одинаково и не говори «на этом слайде».

page — номер страницы, о которой речь. anchor — дословный непрерывный отрывок этой страницы, 3–12 слов, о котором говорится в фразе: по нему подсветится строка. Если фраза о картинке или обобщает — пустая строка.`;
